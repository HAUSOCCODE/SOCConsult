import express from "express";
import cors from "cors";
import helmet from "helmet";
import { env } from "./config/env.js";
import authRoutes from "./routes/authRoutes.js";
import dashboardRoutes from "./routes/dashboardRoutes.js";
import deanRoutes from "./routes/deanRoutes.js";
import availabilityRoutes from "./routes/availabilityRoutes.js";
import appointmentRoutes from "./routes/appointmentRoutes.js";
import attendanceRoutes from "./routes/attendanceRoutes.js";
import scheduleRequestRoutes from "./routes/scheduleRequestRoutes.js";
import notificationRoutes from "./routes/notificationRoutes.js";
import publicRoutes from "./routes/publicRoutes.js";
import taskRoutes from "./routes/taskRoutes.js";
import studentRoutes from "./routes/studentRoutes.js";
import facultyRoutes from "./routes/facultyRoutes.js";
import studentAvailabilityRoutes from "./routes/studentAvailabilityRoutes.js";
import calendarRoutes from "./routes/calendarRoutes.js";
import { errorHandler, notFound } from "./middleware/errorHandler.js";

const app = express();
app.use(helmet());
app.use(cors({ origin: env.clientUrl }));
app.use(express.json({ limit: "2mb" }));
app.get("/", (_req, res) => res.json({ message: "SOCConsult API is running" }));
app.get("/api/health", (_req, res) => res.json({ status: "ok" }));
app.use("/api/auth", authRoutes);
app.use("/api/dashboard", dashboardRoutes);
app.use("/api/dean", deanRoutes);
app.use("/api/availability", availabilityRoutes);
app.use("/api/appointments", attendanceRoutes);
app.use("/api/appointments", appointmentRoutes);
app.use("/api/schedule-requests", scheduleRequestRoutes);
app.use("/api/notifications", notificationRoutes);
app.use("/api/public", publicRoutes);
app.use("/api/tasks", taskRoutes);
app.use("/api/student", studentRoutes);
app.use("/api/faculty", facultyRoutes);
app.use("/api/student-availability", studentAvailabilityRoutes);
app.use("/api/calendar", calendarRoutes);
app.use(notFound);
app.use(errorHandler);
export default app;
